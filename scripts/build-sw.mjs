#!/usr/bin/env node
// The service worker's precache list: app/ -> app/sw-precache.js (the app-shell files the worker saves on
// install, and one hash of their contents = the version) and the version line of app/sw.js (so every
// browser sees a changed worker, even one that does not compare imported scripts when checking for updates).
//
// Run after any change to index.html, styles.css, src/**/*.{js,mjs,css}, icons/, manifest.webmanifest,
// sw-logic.js or data/manifest.json (scripts/build-app-data.mjs rewrites it), and commit both files:
//   node scripts/build-sw.mjs           write app/sw-precache.js and stamp app/sw.js
//   node scripts/build-sw.mjs --check   exit 1 when they are out of date (app/tests/sw.test.mjs checks too)
//
// Data files (data/words-*.json, ...) are not precached: the worker saves each one on first use under its
// ?v=<hash> URL. Audio is saved on first play or from Settings > Offline.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const APP = fileURLToPath(new URL('../app/', import.meta.url));

/** Fixed members of the app shell, relative to app/. */
const FIXED = ['index.html', 'styles.css', 'manifest.webmanifest', 'data/manifest.json'];
/** Folders whose files of these types are part of the shell. */
const TREES = [
  ['src', /\.(m?js|css)$/],
  ['icons', /\.(svg|png)$/],
];
const VERSION_LINE = /^\/\/ Precache version: [0-9a-f]{12} \(stamped by scripts\/build-sw\.mjs.*$/m;

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (entry.isFile()) out.push(path);
  }
  return out;
}

const toUrlPath = (app, path) => relative(app, path).split(sep).join('/');

/** The app-shell files, relative to `app`, sorted (code-point order, stable on every OS). */
export function shellFiles(app = APP) {
  const files = FIXED.filter((f) => existsSync(join(app, f)));
  for (const [dir, pattern] of TREES) {
    if (!existsSync(join(app, dir))) continue;
    for (const path of walk(join(app, dir))) if (pattern.test(path)) files.push(toUrlPath(app, path));
  }
  return [...new Set(files)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** { version, files }: the version is a hash of every file's path and bytes, plus the worker's helpers
 * (a change of caching rules starts from a fresh shell cache). */
export function buildPrecache(app = APP) {
  const files = shellFiles(app);
  for (const required of ['index.html', 'data/manifest.json']) {
    if (!files.includes(required)) throw new Error(`app shell incomplete: ${required} is missing in ${app}`);
  }
  const hash = createHash('sha256');
  for (const file of [...files, 'sw-logic.js']) {
    const path = join(app, file);
    if (!existsSync(path)) continue;
    hash.update(`${file}\0`);
    hash.update(readFileSync(path));
    hash.update('\0');
  }
  return { version: hash.digest('hex').slice(0, 12), files };
}

/** Source of app/sw-precache.js. */
export function precacheSource({ version, files }) {
  return [
    '// Generated by scripts/build-sw.mjs: the app-shell files the service worker saves on install and the',
    '// hash of their contents. Do not edit; run `node scripts/build-sw.mjs` after changing the app shell.',
    `self.SW_PRECACHE = ${JSON.stringify({ version, files }, null, 2)};`,
    '',
  ].join('\n');
}

/** app/sw.js with its version line set to `version`. */
export function stampWorker(source, version) {
  if (!VERSION_LINE.test(source)) throw new Error('app/sw.js: the "// Precache version: …" line is missing');
  return source.replace(VERSION_LINE, `// Precache version: ${version} (stamped by scripts/build-sw.mjs, so every browser sees a changed worker)`);
}

/** What the two files should contain now, and whether they do. */
export function precacheStatus(app = APP) {
  const precache = buildPrecache(app);
  const precachePath = join(app, 'sw-precache.js');
  const workerPath = join(app, 'sw.js');
  const wantPrecache = precacheSource(precache);
  const worker = readFileSync(workerPath, 'utf8');
  const wantWorker = stampWorker(worker, precache.version);
  const havePrecache = existsSync(precachePath) ? readFileSync(precachePath, 'utf8') : null;
  return {
    ...precache,
    precachePath,
    workerPath,
    wantPrecache,
    wantWorker,
    upToDate: havePrecache === wantPrecache && worker === wantWorker,
  };
}

function main(args) {
  const status = precacheStatus();
  if (args.includes('--check')) {
    if (status.upToDate) {
      console.log(`sw-precache.js is up to date (version ${status.version}, ${status.files.length} files)`);
      return 0;
    }
    console.error('app/sw-precache.js or the version line of app/sw.js is out of date: run `node scripts/build-sw.mjs`');
    return 1;
  }
  writeFileSync(status.precachePath, status.wantPrecache);
  writeFileSync(status.workerPath, status.wantWorker);
  console.log(`app/sw-precache.js: version ${status.version}, ${status.files.length} files${status.upToDate ? ' (unchanged)' : ''}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exitCode = main(process.argv.slice(2));
